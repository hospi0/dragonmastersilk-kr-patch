JOSA = [('은', '는'), ('이', '가'), ('을', '를'), ('과', '와'), ('이랑', '랑'), ('이나', '나'), ('으로', '로')]


def josa(t, i, word):
    """t[i:] 앞이 word 로 바뀐 뒤 붙은 조사를 word 받침에 맞춤(으로/로: ㄹ 받침은 로)"""
    jong = (ord(word[-1]) - 0xAC00) % 28 if '가' <= word[-1] <= '힣' else 0
    for a, b in JOSA:
        for x in (a, b):
            if t.startswith(x, i) and not ('가' <= t[i + len(x):i + len(x) + 1] <= '힣' and x in ('이', '가')):
                y = a if jong and not (a == '으로' and jong == 8) else b
                return t[:i] + y + t[i + len(x):]
    return t


def unify(no, src, t):
    for s, pat, rep in UNIFY:
        if s not in src: continue
        while True:
            m = re.search(pat, t)
            if not m: break
            t = josa(t[:m.start()] + rep + t[m.end():], m.start() + len(rep), rep)
    if no in HDR and t.startswith('（'):
        t = '（' + HDR[no] + t[t.index('）'):]
    return t


def clean(t):
    """엑셀식 따옴표 감싸기("…") 벗김 · {N} → \\n"""
    if len(t) > 1 and t[0] == '"' and t[-1] == '"': t = t[1:-1].replace('""', '"')
    return t.replace('{N}', '\\n')


def rows(p):
    """번역 칸에 \\n 대신 «진짜 줄바꿈»이 들어간 파일(03·04·09·10·15~18) → 번호로 시작하지 않는 줄은 앞 줄에 \\n 으로 이음.
       21 은 \\n 이 두 번 적힘(\\\\n) → \\n 으로."""
    t = open(p, encoding='utf-8-sig').read().replace('\r\n', '\n').split('\n')
    out = []
    for l in t[1:]:
        if re.match(r'\d{5}\t', l) or not out: out.append(l)
        elif l.strip() or l: out[-1] += '\\n' + l
    out = [l.replace('\\\\n', '\\n') for l in out if l.strip()]
    return t[0], [l.split('\t') for l in out]


